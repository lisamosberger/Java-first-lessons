package com.selfstudies;

public class Datatype {
    static void main() {
        //DATA TYPES

        //Whole numbers
        byte myByte = 100;
        short myShort = 1000;
        int myInt = 42;
        long myLong = 100000L;

        //Decimal numbers
        float myFloat = 3.14f;
        double myDouble = 3.14234;

        //One character
        char myChar = 'a';

        //True or false
        boolean myBoolean = true;

        //Text
        String myString = "Hello World";

        //var = Java automatically determines the data type

        //=========================
        //COMMON OPERATORS

        // + addition
        // - subtraction
        // * multiplication
        // / division
        // % modulo

        // == equal to
        // != not equal to
        // > greater than
        // < less than
        // >= greater than or equal to
        // <= less than or equal to

        // && AND
        // || OR
        // ! NOT

    }
}
